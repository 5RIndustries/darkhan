/**
 * Darkhan — Instance Identity Service
 *
 * [MYTHOS DEFENSE] Manages the Ed25519 keypair for this Darkhan instance.
 * Every outbound message is signed with the private key. Federation peers
 * verify signatures using the public key. This prevents:
 *   - Message forgery (attacker can't sign messages as this instance)
 *   - Tampering in transit (signature verification fails if body is modified)
 *   - Identity spoofing between federated instances
 *
 * The keypair is generated at first startup and stored in the database.
 * The private key NEVER leaves the instance. The public key is shared
 * with federation peers during the handshake.
 *
 * Message trust levels:
 *   - human_verified:    typed by an authenticated human (highest trust)
 *   - agent_local:       generated by a worker on this node
 *   - agent_federated:   received from a federated peer (trust degrades)
 *   - external:          from Telegram, API, or unknown source (lowest trust)
 *   - quarantined:       flagged by two-LLM consensus disagreement
 */

const crypto = require('crypto');

class InstanceIdentity {
  constructor({ db, config, activityLog }) {
    this.db = db;
    this.config = config;
    this.activityLog = activityLog;
    this.publicKey = null;
    this.privateKey = null;
    this.instanceId = config.federation?.instanceId || 'standalone';
  }

  /**
   * Initialize: load or generate the Ed25519 keypair.
   * Call this at server startup.
   */
  async initialize() {
    return new Promise((resolve, reject) => {
      // Ensure the table exists
      this.db.run(`CREATE TABLE IF NOT EXISTS instance_identity (
        key TEXT PRIMARY KEY, value TEXT NOT NULL, created_at DATETIME DEFAULT CURRENT_TIMESTAMP
      )`, (err) => {
        if (err) return reject(err);

        // Try to load existing keypair
        this.db.get('SELECT value FROM instance_identity WHERE key = ?', ['ed25519_public'], (err, pubRow) => {
          if (err) return reject(err);

          if (pubRow) {
            // Keypair exists — load it
            this.publicKey = pubRow.value;
            this.db.get('SELECT value FROM instance_identity WHERE key = ?', ['ed25519_private'], (err2, privRow) => {
              if (err2 || !privRow) return reject(new Error('Public key exists but private key missing'));
              this.privateKey = privRow.value;
              console.log(`[Identity] Ed25519 keypair loaded (instance: ${this.instanceId})`);
              console.log(`[Identity] Public key: ${this.publicKey.substring(0, 20)}...`);
              resolve();
            });
          } else {
            // Generate new keypair
            this._generateKeypair()
              .then(() => resolve())
              .catch(reject);
          }
        });
      });
    });
  }

  /**
   * Generate a new Ed25519 keypair and store it.
   */
  async _generateKeypair() {
    return new Promise((resolve, reject) => {
      const { publicKey, privateKey } = crypto.generateKeyPairSync('ed25519', {
        publicKeyEncoding: { type: 'spki', format: 'pem' },
        privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
      });

      this.publicKey = publicKey;
      this.privateKey = privateKey;

      // Store in database
      this.db.run('INSERT INTO instance_identity (key, value) VALUES (?, ?)',
        ['ed25519_public', publicKey], (err) => {
          if (err) return reject(err);
          this.db.run('INSERT INTO instance_identity (key, value) VALUES (?, ?)',
            ['ed25519_private', privateKey], (err2) => {
              if (err2) return reject(err2);

              console.log(`[Identity] Ed25519 keypair GENERATED (instance: ${this.instanceId})`);
              console.log(`[Identity] Public key: ${publicKey.substring(0, 40)}...`);

              if (this.activityLog) {
                this.activityLog.append({
                  actor: 'system',
                  action: 'keypair_generated',
                  details: JSON.stringify({
                    instanceId: this.instanceId,
                    algorithm: 'ed25519',
                    publicKeyFingerprint: crypto.createHash('sha256')
                      .update(publicKey).digest('hex').substring(0, 16),
                  }),
                });
              }

              resolve();
            });
        });
    });
  }

  /**
   * Sign a message. Returns the base64-encoded Ed25519 signature.
   * The signed data is: id + from_user + body + trust_level
   */
  sign(messageId, fromUser, body, trustLevel) {
    if (!this.privateKey) return null;

    const data = `${messageId}|${fromUser}|${body}|${trustLevel}`;
    const sign = crypto.createSign ? null : null; // Ed25519 uses sign() directly

    try {
      const privateKeyObj = crypto.createPrivateKey(this.privateKey);
      const signature = crypto.sign(null, Buffer.from(data), privateKeyObj);
      return signature.toString('base64');
    } catch (err) {
      console.error('[Identity] Signing failed:', err.message);
      return null;
    }
  }

  /**
   * Verify a message signature. Returns true if valid.
   * Used when receiving federated messages from other instances.
   */
  verify(messageId, fromUser, body, trustLevel, signature, peerPublicKey) {
    if (!signature || !peerPublicKey) return false;

    const data = `${messageId}|${fromUser}|${body}|${trustLevel}`;

    try {
      const publicKeyObj = crypto.createPublicKey(peerPublicKey);
      return crypto.verify(null, Buffer.from(data), publicKeyObj, Buffer.from(signature, 'base64'));
    } catch (err) {
      console.error('[Identity] Verification failed:', err.message);
      return false;
    }
  }

  /**
   * Determine the trust level for a message based on its origin.
   */
  determineTrustLevel(fromUser, origin) {
    if (origin === 'federated') return 'agent_federated';
    if (origin === 'external') return 'external';

    // Local messages
    if (fromUser && fromUser.startsWith('agent_')) return 'agent_local';
    if (fromUser && fromUser.startsWith('user_')) return 'human_verified';
    if (fromUser && fromUser.startsWith('system_')) return 'agent_local';

    return 'external'; // Unknown origin defaults to lowest trust
  }

  /**
   * Get the public key for sharing with federation peers.
   */
  getPublicKey() {
    return this.publicKey;
  }

  /**
   * Get the public key fingerprint (for display/logging).
   */
  getFingerprint() {
    if (!this.publicKey) return null;
    return crypto.createHash('sha256').update(this.publicKey).digest('hex').substring(0, 16);
  }

  /**
   * Get instance identity info for API responses.
   */
  getInfo() {
    return {
      instanceId: this.instanceId,
      algorithm: 'ed25519',
      publicKey: this.publicKey,
      fingerprint: this.getFingerprint(),
    };
  }
}

module.exports = { InstanceIdentity };
